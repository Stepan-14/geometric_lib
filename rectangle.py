def area(a, b): 
    # Принимает чила a и b - длины сторон прямоугольника
    # и возвращает произведение a и b - площадь прямоугольника
    return a * b 

def perimeter(a, b): 
    # Принимает чила a и b - длины сторон прямоугольника
    # и возвращает сумму удвоенных значений a и b - периметр прямоугольника
    return a * 2 + b * 2